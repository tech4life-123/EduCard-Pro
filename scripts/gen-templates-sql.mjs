// Generates supabase/migrations/20261005000005_starter_templates.sql from scripts/starters.mjs
import { writeFileSync } from "node:fs";
import { STARTERS } from "./starters.mjs";

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = STARTERS.map((t) => `(
  null, ${q(t.slug)}, ${q(t.name)}, ${q(t.category)}, ${q(t.orientation)},
  ${t.width_mm}, ${t.height_mm}, ${t.photo_width_mm}, ${t.photo_height_mm},
  $json$${JSON.stringify(t.front)}$json$::jsonb,
  $json$${JSON.stringify(t.back)}$json$::jsonb,
  ${t.sort_order}
)`).join(",\n");

const sql = `-- EduCard Pro — starter card templates (Phase 4). GENERATED by scripts/gen-templates-sql.mjs; edit scripts/starters.mjs instead.
-- Global templates (organization_id is null) are platform-managed and read-only to organizations.
insert into public.card_templates
  (organization_id, slug, name, category, orientation, width_mm, height_mm, photo_width_mm, photo_height_mm, front_design, back_design, sort_order)
values
${rows}
on conflict (slug) where organization_id is null do update set
  name = excluded.name, category = excluded.category, orientation = excluded.orientation,
  width_mm = excluded.width_mm, height_mm = excluded.height_mm,
  photo_width_mm = excluded.photo_width_mm, photo_height_mm = excluded.photo_height_mm,
  front_design = excluded.front_design, back_design = excluded.back_design,
  sort_order = excluded.sort_order, version = public.card_templates.version + 1;
`;
writeFileSync(new URL("../supabase/migrations/20261005000005_starter_templates.sql", import.meta.url), sql);
console.log("wrote migration for", STARTERS.length, "templates");
